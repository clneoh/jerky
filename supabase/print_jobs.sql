-- supabase/print_jobs.sql — the queue a label takes from a phone to the Mac's print bridge.
--
-- ⭐ WHY A QUEUE AND NOT A DIRECT CALL. Her printer is a Wi-Fi Gprinter GP-1326D: TSPL over raw TCP,
-- ⚠️ with no IPP/AirPrint and no HTTP page. A web page cannot open a raw socket, and an HTTPS page cannot
-- call a plain-HTTP device on her LAN (mixed content). ⭐ So the phone writes a job here, over HTTPS, and a
-- small bridge on the Mac (which CAN reach the printer on port 9100) prints it. The same route works on
-- Android and iOS, with no certificate or address to configure on the phone.
--
-- RUN THIS ONCE, in the Supabase SQL editor. It only creates a table; nothing existing is touched.

create table if not exists public.print_jobs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  status text not null default 'new',      -- new | printed | failed
  site text not null default 'main',       -- which bridge prints it (two sites, one book)
  attempts int not null default 0,
  payload jsonb not null,                  -- { widthMm, heightMm, widthBytes, height, data(base64) }
  printed_at timestamptz
);

-- ⚠️⚠️ FROM 30 OCTOBER 2026 A NEW TABLE IS NOT EXPOSED TO THE DATA API UNLESS IT IS GRANTED (v617). ⚠️ Supabase
-- stops auto-granting to `authenticated` on new tables; without these lines the app and the bridge would get
-- 42501 ("permission denied") on a table that exists and has policies. ⭐ The grants below are what Supabase
-- used to add for us; RLS still decides WHICH ROWS, so nothing is exposed by the grant itself.
grant select, insert, update, delete on public.print_jobs to authenticated;
-- The identity column draws its number from this sequence; PostgREST inserts need it too.
grant usage, select on sequence public.print_jobs_id_seq to authenticated;
-- ⚠️ And the public anon key gets nothing: no sign-in, no queue.
revoke all on public.print_jobs from anon;
revoke all on sequence public.print_jobs_id_seq from anon;

-- ⚠️ AND FOR A TABLE THAT ALREADY EXISTS (the first version had no site): this adds it. Two sites, one book —
-- ⚠️ **without it every bridge prints every label, twice.** ⚠️ An old job's default is `main`.
alter table public.print_jobs add column if not exists site text not null default 'main';

alter table public.print_jobs enable row level security;

-- ⚠️ A JOB IS HER OWN BUSINESS DATA: only a signed-in user (her devices and the bridge, which signs in as
-- her) may see or move one. The public anon key alone gets nothing.
drop policy if exists "print jobs read" on public.print_jobs;
create policy "print jobs read" on public.print_jobs
  for select to authenticated using (true);

drop policy if exists "print jobs insert" on public.print_jobs;
create policy "print jobs insert" on public.print_jobs
  for insert to authenticated with check (true);

drop policy if exists "print jobs update" on public.print_jobs;
create policy "print jobs update" on public.print_jobs
  for update to authenticated using (true) with check (true);

drop policy if exists "print jobs delete" on public.print_jobs;
create policy "print jobs delete" on public.print_jobs
  for delete to authenticated using (true);

create index if not exists print_jobs_status_site_created
  on public.print_jobs (status, site, created_at);

-- ⭐ A READ-BACK, so she can SEE that it worked rather than being told.
select
  (select count(*) from information_schema.tables
    where table_schema = 'public' and table_name = 'print_jobs') as table_exists,
  (select count(*) from pg_policies
    where schemaname = 'public' and tablename = 'print_jobs') as policy_count,
  (select count(*) from information_schema.role_table_grants
    where table_schema = 'public' and table_name = 'print_jobs'
      and grantee = 'authenticated' and privilege_type = 'SELECT') as signed_in_can_read,
  (select count(*) from information_schema.columns
    where table_schema = 'public' and table_name = 'print_jobs'
      and column_name = 'site') as site_column;
