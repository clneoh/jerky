-- supabase/waitlist.sql — "tell me when a day frees up": the waitlist for a full bake day.
--
-- ⭐ WHY A TABLE AND NOT A WHATSAPP LINK. A customer on a sold-out day can already message her — but then the
-- request lives in a chat, and when a pan frees she has to remember who asked. ⭐ A row here lets the day say
-- WHO wanted it, and lets her message exactly those people in one pass. ⚠️ It is the last level of the customer
-- plan (P5, "the not-yet").
--
-- RUN THIS ONCE, in the Supabase SQL editor. It only creates a table; nothing existing is touched.

create table if not exists public.waitlist (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  day date not null,                          -- the bake day they asked about
  name text not null default '',
  whatsapp text not null,
  handled boolean not null default false,     -- she has messaged them (or the day has gone)
  handled_at timestamptz
);

-- ⚠️⚠️ A CUSTOMER IS NOT SIGNED IN, SO `anon` MUST BE ABLE TO INSERT — and ⚠️ **nothing more.**
-- ⭐ THE ASYMMETRY IS THE WHOLE DESIGN: **anyone may add themselves; nobody anonymous may read the list**,
-- because every other row is somebody else's phone number.
--
-- ⚠️⚠️ AND THE REVOKE MUST COME FIRST — MEASURED ON HER PROJECT, 25 Oct: after the first version of this file,
-- the read-back said **`anon_can_read = true`**. ⭐ **Supabase grants `ALL` to `anon` on every new table in
-- `public` by DEFAULT**, so the grant was there without one line in this file asking for it. RLS still refused
-- the rows (no anon policy), so nothing leaked — ⚠️ **but a grant that exists is one careless policy away from a
-- leak of every customer's phone number.** ⭐ So the default is taken away first and the one permission she
-- needs is given back by name.
revoke all on public.waitlist from anon;
grant insert on public.waitlist to anon;
-- ⚠️ The identity column draws from this sequence, and an INSERT without a grant on it fails with 42501.
grant usage on sequence public.waitlist_id_seq to anon;

-- From 30 October 2026 a new table is not exposed to the Data API unless it is granted (the print_jobs note).
-- ⭐ Her own phones are signed in, so they get the whole row — read it, tick it, delete it.
grant select, update, delete on public.waitlist to authenticated;
grant usage, select on sequence public.waitlist_id_seq to authenticated;

alter table public.waitlist enable row level security;

-- ⭐ ANYONE MAY ADD THEMSELVES. ⚠️ `with check (true)` is not a hole: the columns below are typed and limited,
-- and there is nothing to read back afterwards with this key.
drop policy if exists "waitlist insert" on public.waitlist;
create policy "waitlist insert" on public.waitlist
  for insert to anon, authenticated with check (true);

-- ⭐ ONLY SHE MAY SEE, TICK OR DELETE — the list is other people's numbers.
drop policy if exists "waitlist read" on public.waitlist;
create policy "waitlist read" on public.waitlist
  for select to authenticated using (true);

drop policy if exists "waitlist update" on public.waitlist;
create policy "waitlist update" on public.waitlist
  for update to authenticated using (true) with check (true);

drop policy if exists "waitlist delete" on public.waitlist;
create policy "waitlist delete" on public.waitlist
  for delete to authenticated using (true);

create index if not exists waitlist_open_days
  on public.waitlist (day, handled);

-- ⭐ A READ-BACK, so she can SEE that it worked rather than being told.
select
  to_regclass('public.waitlist') is not null                       as table_exists,
  (select count(*) from pg_policies
     where schemaname = 'public' and tablename = 'waitlist')        as policy_count,
  has_table_privilege('anon', 'public.waitlist', 'INSERT')          as anon_can_add,
  has_table_privilege('anon', 'public.waitlist', 'SELECT')          as anon_can_read;
